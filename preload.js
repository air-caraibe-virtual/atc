const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('sim', {
  onTelemetry: (cb) => ipcRenderer.on('telemetry', (_e, d) => cb(d)),
  onStatus: (cb) => ipcRenderer.on('sim-status', (_e, d) => cb(d)),
  state: () => ipcRenderer.invoke('sim-state'),
  simbrief: (user) => ipcRenderer.invoke('simbrief', user),
  metar: (icaos) => ipcRenderer.invoke('metar', icaos),
  airport: (icao) => ipcRenderer.invoke('airport', icao),
  datis: (icao) => ipcRenderer.invoke('datis', icao),
  radarFrames: () => ipcRenderer.invoke('radar-frames'),
  liveFlights: (lat, lon) => ipcRenderer.invoke('live-flights', lat, lon),
  aiModels: () => ipcRenderer.invoke('ai-models'),
  aiSpawn: (id, title, livery, tail, p) => ipcRenderer.invoke('ai-spawn', id, title, livery, tail, p),
  aiMove: (list) => ipcRenderer.send('ai-move', list),
  aiRemove: (id) => ipcRenderer.invoke('ai-remove', id),
  aiClear: () => ipcRenderer.invoke('ai-clear'),
  onAiStatus: (cb) => ipcRenderer.on('ai-status', (_e, d) => cb(d)),
  notams: (icao) => ipcRenderer.invoke('notams', icao),
  airportParking: (icao) => ipcRenderer.invoke('airport-parking', icao),
  airportApproaches: (icao) => ipcRenderer.invoke('airport-approaches', icao),
  nearestAirport: (lat, lon) => ipcRenderer.invoke('nearest-airport', lat, lon),
  airportLayout: (icao, lat, lon) => ipcRenderer.invoke('airport-layout', icao, lat, lon),
  setCom1: (mhz, method) => ipcRenderer.invoke('set-com1', mhz, method),
  pushback: (face) => ipcRenderer.invoke('pushback', face),
  pushbackStop: () => ipcRenderer.invoke('pushback-stop'),
  onPushStatus: (cb) => ipcRenderer.on('push-status', (_e, d) => cb(d)),
  setSquawk: (code) => ipcRenderer.invoke('set-squawk', code),
  tts: (text, voice, rate, pitch) => ipcRenderer.invoke('tts', text, voice, rate, pitch),
  aiChat: (o) => ipcRenderer.invoke('ai-chat', o),
  aiPrepareLocal: () => ipcRenderer.invoke('ai-prepare-local'),
  ollamaTags: () => ipcRenderer.invoke('ollama-tags'),
  onAiProgress: (cb) => ipcRenderer.on('ai-progress', (_e, d) => cb(d)),
  sttPrepare: (model) => ipcRenderer.invoke('stt-prepare', model),
  sttTranscribe: (samples, langs) => ipcRenderer.invoke('stt-transcribe', samples, langs),
  onSttProgress: (cb) => ipcRenderer.on('stt-progress', (_e, d) => cb(d)),
  micShortcut: (accel) => ipcRenderer.invoke('mic-shortcut', accel),
  onMicKey: (cb) => { ['mic-press', 'mic-hold', 'mic-release'].forEach((ch) => ipcRenderer.on(ch, () => cb(ch.slice(4)))); },
  quitApp: () => ipcRenderer.invoke('app-quit'),
  appVersion: () => ipcRenderer.invoke('app-version'),
  updateAttention: (o) => ipcRenderer.invoke('update-attention', o),
  onUpdateShow: (cb) => ipcRenderer.on('update-show', () => cb()),
  updateCheck: (beta) => ipcRenderer.invoke('update-check', beta),
  updateInstall: (url, version) => ipcRenderer.invoke('update-install', url, version),
  onUpdateProgress: (cb) => ipcRenderer.on('update-progress', (_e, d) => cb(d)),
  openUrl: (url) => ipcRenderer.invoke('open-url', url),
});
